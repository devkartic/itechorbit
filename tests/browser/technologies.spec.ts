import { test, expect } from '@playwright/test';

test('homepage toolkit filters in place and links to a persistent services filter', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const toolkit = page.getByRole('region', { name: 'Filter homepage services by technology' });
  const services = page.locator('#homepage-services');
  const laravel = toolkit.getByRole('button', { name: 'Laravel', exact: true });
  const all = toolkit.getByRole('button', { name: 'All', exact: true });
  await expect(all).toHaveAttribute('aria-pressed', 'true');
  await expect(toolkit.getByRole('button').first()).toHaveText('All');
  const allTitles = await services.locator('.service-card h3').allTextContents();
  const allCount = await services.getByRole('status').textContent();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await laravel.focus();
  await page.keyboard.press('Enter');
  await expect(laravel).toHaveAttribute('aria-pressed', 'true');
  await expect(all).toHaveAttribute('aria-pressed', 'false');
  await expect(page).toHaveURL('http://127.0.0.1:8010/');
  await expect(services.getByRole('status')).toContainText('Laravel');
  const filteredTitles = await services.locator('.service-card h3').allTextContents();
  expect(filteredTitles).not.toEqual(allTitles);
  expect(filteredTitles.length).toBeLessThanOrEqual(6);
  await page.screenshot({ path: testInfo.outputPath('homepage-technology-filter.png'), fullPage: true });
  await all.focus();
  await page.keyboard.press('Enter');
  await expect(all).toHaveAttribute('aria-pressed', 'true');
  await expect(services.getByRole('status')).toHaveText(allCount ?? '');
  await expect(services.getByRole('link', { name: 'All services', exact: true })).toHaveAttribute('href', '/service/info');
  await expect(page).toHaveURL('http://127.0.0.1:8010/');
  await expect(laravel).toHaveAttribute('aria-pressed', 'false');
  expect(await services.locator('.service-card h3').allTextContents()).toEqual(allTitles);
  await laravel.click();
  await services.getByRole('link', { name: 'View all Laravel services' }).click();
  await expect(page).toHaveURL(/\/service\/info\?technology=laravel$/);
  const filters = page.getByRole('navigation', { name: 'Filter services by technology' });
  await expect(filters.getByRole('link', { name: 'Laravel', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', /noindex/);
  await page.reload();
  await expect(filters.getByRole('link', { name: 'Laravel', exact: true })).toHaveAttribute('aria-current', 'page');
  await page.screenshot({ path: testInfo.outputPath('services-technology-filter.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await filters.getByRole('link', { name: 'All services', exact: true }).click();
  await expect(page).toHaveURL(/\/service\/info$/);
  await page.goBack();
  await expect(page).toHaveURL(/\?technology=laravel$/);
  await expect(filters.getByRole('link', { name: 'Laravel', exact: true })).toHaveAttribute('aria-current', 'page');
  await page.goto('/services/laravel-development');
  await page.getByRole('link', { name: 'Laravel', exact: true }).click();
  await expect(page).toHaveURL(/\/service\/info\?technology=laravel$/);
  expect(errors).toEqual([]);
});

test('services combine related tools into one clickable filter', async ({ page }) => {
  await page.goto('/service/info');
  const filters = page.getByRole('navigation', { name: 'Filter services by technology' });
  const seo = filters.getByRole('link', { name: 'SEO', exact: true });
  await expect(seo).toBeVisible();
  for (const child of ['Google Search Console', 'Google Analytics 4', 'XML sitemaps', 'Structured data']) {
    await expect(filters.getByRole('link', { name: child, exact: true })).toHaveCount(0);
  }
  await seo.focus();
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/\/service\/info\?technology=seo$/);
  await expect(seo).toHaveAttribute('aria-current', 'page');
  await expect(page.getByRole('status')).toContainText('SEO');
  await expect(page.locator('.service-card h3')).toContainText(['Technical SEO Optimization', 'Google Analytics & Tag Manager']);
  await page.reload();
  await expect(seo).toHaveAttribute('aria-current', 'page');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await filters.getByRole('link', { name: 'All services', exact: true }).click();
  await expect(page).toHaveURL(/\/service\/info$/);
  await expect(filters.getByRole('link', { name: 'All services', exact: true })).toHaveAttribute('aria-current', 'page');
  await page.goBack();
  await expect(seo).toHaveAttribute('aria-current', 'page');
});

test('Website Control manages technologies and searchable service assignments', async ({ page }, testInfo) => {
  const name = `Browser Tool ${testInfo.project.name}`;
  const slug = `browser-tool-${testInfo.project.name}`;
  const serviceTitle = `Technology Service ${testInfo.project.name}`;
  let serviceUrl: string | undefined;
  await page.goto('/login');
  await page.getByLabel('Email address').fill('admin@example.test');
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-password-42');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/home$/);
  await page.goto('/website-technologies/create');
  await page.getByLabel('Name *', { exact: true }).fill(name);
  await page.getByLabel('URL slug *').fill(slug);
  await page.getByLabel('Display order').fill('0');
  await page.getByRole('switch', { name: 'Show in homepage toolkit' }).check();
  await expect(page.getByRole('switch', { name: 'Show in services filters' })).toBeChecked();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page).toHaveURL(/\/website-technologies$/);
  const edit = page.getByRole('link', { name: `Edit ${name}`, exact: true });
  const technologyUrl = (await edit.getAttribute('href'))!.replace(/\/edit$/, '');
  try {
    await page.goto('/service-info/create');
    await page.getByLabel('Title *', { exact: true }).fill(serviceTitle);
    await page.getByLabel('URL slug *').fill(`technology-service-${testInfo.project.name}`);
    await page.getByLabel('Summary *').fill('A service used to verify technology assignments.');
    await page.getByRole('textbox', { name: 'Description *', exact: true }).fill('A synthetic service for browser verification.');
    const search = page.getByRole('searchbox', { name: 'Search technologies' });
    await search.fill(name);
    await page.getByRole('checkbox', { name, exact: true }).check();
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(page).toHaveURL(/\/service-info$/);
    serviceUrl = (await page.getByRole('link', { name: `Edit ${serviceTitle}`, exact: true }).getAttribute('href'))!.replace(/\/edit$/, '');
    await page.goto(`${serviceUrl}/edit`);
    await expect(page.getByRole('checkbox', { name, exact: true })).toBeChecked();
    await page.goto('/');
    await page.getByRole('button', { name, exact: true }).click();
    await expect(page.locator('#homepage-services .service-card h3')).toHaveText([serviceTitle]);
    await page.goto('/website-technologies');
    await page.getByRole('button', { name: `Delete ${name}`, exact: true }).click();
    await page.getByRole('button', { name: 'Delete record', exact: true }).click();
    await expect(page.getByText(/Remove this technology from its services/)).toBeVisible();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.goto(`${technologyUrl}/edit`);
    await page.getByRole('switch', { name: 'Published / active' }).uncheck();
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(page).toHaveURL(/\/website-technologies$/);
    await page.goto('/');
    await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0);
    await page.goto(`${serviceUrl}/edit`);
    const inactive = page.getByRole('checkbox', { name: `${name} (inactive)`, exact: true });
    await expect(inactive).toBeChecked();
    await inactive.uncheck();
    await expect(inactive).toBeDisabled();
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    await expect(page).toHaveURL(/\/service-info$/);
    await page.goto(`${serviceUrl}/edit`);
    await expect(page.getByRole('checkbox', { name: `${name} (inactive)`, exact: true })).toHaveCount(0);
  } finally {
    const token = await page.locator('meta[name="csrf-token"]').getAttribute('content');
    const headers = { 'X-CSRF-TOKEN': token ?? '', Accept: 'application/json' };
    if (serviceUrl) expect((await page.request.delete(serviceUrl, { headers })).ok()).toBeTruthy();
    if (technologyUrl) expect((await page.request.delete(technologyUrl, { headers })).ok()).toBeTruthy();
  }
});


test('Website Control renames and merges catalog entries while preserving old URLs', async ({ page }, testInfo) => {
  const name = `Merge Tool ${testInfo.project.name}`;
  const slug = `merge-tool-${testInfo.project.name}`;
  await page.goto('/login');
  await page.getByLabel('Email address').fill('admin@example.test');
  await page.getByLabel('Password', { exact: true }).fill('Browser-test-password-42');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/home$/);
  await page.goto('/website-technologies/create');
  await page.getByLabel('Name *', { exact: true }).fill(name);
  await page.getByLabel('URL slug *').fill(slug);
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page).toHaveURL(/\/website-technologies$/);
  await page.getByRole('link', { name: `Edit ${name}`, exact: true }).click();
  await page.getByLabel('URL slug *').fill(`${slug}-renamed`);
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page).toHaveURL(/\/website-technologies$/);
  await page.getByRole('link', { name: `Edit ${name}`, exact: true }).click();
  await page.getByLabel('Merge into', { exact: true }).selectOption({ label: 'Laravel' });
  await page.getByRole('button', { name: 'Merge technology', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Merge this technology?' });
  await expect(dialog).toContainText(name);
  await dialog.getByRole('button', { name: 'Confirm merge' }).click();
  await expect(page).toHaveURL(/\/website-technologies$/);
  await expect(page.getByRole('link', { name: `Edit ${name}`, exact: true })).toHaveCount(0);
  await page.goto(`/service/info?technology=${slug}`);
  await expect(page).toHaveURL(/\/service\/info\?technology=laravel$/);
  await page.goto(`/service/info?technology=${slug}-renamed`);
  await expect(page).toHaveURL(/\/service\/info\?technology=laravel$/);
});
